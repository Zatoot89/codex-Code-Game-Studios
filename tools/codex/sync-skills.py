#!/usr/bin/env python3
"""Generate native Codex skill adapters from canonical .claude/skills names."""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".claude" / "skills"
TARGET = ROOT / ".agents" / "skills"
MARKER = "GENERATED by tools/codex/sync-skills.py"

def description(name: str) -> str:
    return "Use when asked to perform Game Studios " + name.replace("-", " ") + " tasks."

def render(name: str) -> str:
    lines = [
        "---", "name: " + name,
        "description: " + json.dumps(description(name), ensure_ascii=False),
        "---", "",
        "<!-- GENERATED by tools/codex/sync-skills.py; do not edit directly. -->", "",
        "# Game Studios skill: " + name, "",
        "Canonical workflow: .claude/skills/" + name + "/SKILL.md", "",
        "1. Read and follow the entire canonical SKILL.md before acting; inspect its referenced files as necessary.",
        "2. Honor AGENTS.md, CLAUDE.md, project.yaml, and the collaboration approval protocol.",
        "3. Adapt Claude-specific hooks, command expansions, and agent tools to the available runtime; never claim an unavailable test or tool succeeded.",
        "4. Do not push, open a pull request, merge, or execute expensive CI without authorization.",
        "5. Treat the user's task description as the skill arguments; do not rely on Claude-only $ARGUMENTS interpolation.",
        ""
    ]
    return "\n".join(lines)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify adapters without modifying files")
    args = parser.parse_args()
    sources = sorted(SOURCE.glob("*/SKILL.md"))
    if not sources:
        print("No canonical skills found", file=sys.stderr)
        return 1
    expected = {TARGET / p.parent.name / "SKILL.md": render(p.parent.name) for p in sources}
    issues = []
    for path, content in expected.items():
        actual = path.read_text(encoding="utf-8") if path.is_file() else None
        if actual == content:
            continue
        if actual is not None and MARKER not in actual:
            issues.append(f"Refusing to overwrite non-generated skill: {path}")
        elif args.check:
            issues.append(f"Missing or stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for path in TARGET.glob("*/SKILL.md"):
        if path not in expected and MARKER in path.read_text(encoding="utf-8"):
            if args.check:
                issues.append(f"Stale generated skill: {path}")
            else:
                path.unlink()
                try:
                    path.parent.rmdir()
                except OSError:
                    pass
    for issue in issues:
        print(issue, file=sys.stderr)
    print(f"{'checked' if args.check else 'synced'} {len(expected)} native Codex skills")
    return 1 if issues else 0

if __name__ == "__main__":
    sys.exit(main())
